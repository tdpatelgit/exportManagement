@job_ins_bp.route("/<int:job_in_id>/versions/<int:version_number>")
@admin_required
def view_job_in_version(job_in_id, version_number):
    container = current_app.container
    try:
        container.job_in_service.get(job_in_id, g.user.company_id)  # tenant-scope check
        historical_job_in, version = container.document_version_service.get_version(
            "job_in", job_in_id, version_number
        )
        sheet = container.job_in_service.build_sheet(historical_job_in, g.user.company_id)
    except (NotFoundError, ValidationError):
        abort(404)
    return render_template(
        "job_ins/print.html", job_in=historical_job_in, historical_version=version, **sheet
    )
